#!/usr/bin/env node
// sync-brand-tokens.mjs — one token source for the hub and the decks. Reads the vendored
// Nagarro Master Slides tokens (Carolina Baptista; Figma variable names with "/" as "-") and
// writes src/styles/brand-tokens.css: the Theme colours for light (:root, .nb-light) and dark
// (.nb-dark), and the spacing, radius, layout and weight scales. The shell's --n-* primitives
// alias these (src/styles/base.css), so the hub speaks the same token language as the decks.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const tokensPath = resolve(root, 'public/vendor/nagarro-master-slides/tokens.json')
const t = JSON.parse(readFileSync(tokensPath, 'utf8'))
const colors = t.color.tokens
const byName = Object.fromEntries(colors.map((c) => [c.name, c]))
const valueFor = (tok, theme, depth = 0) => {
  if (depth > 6) throw new Error(`alias loop at ${tok.name}`)
  let v = typeof tok.value === 'string' ? tok.value : tok.value[theme] ?? tok.value.light ?? Object.values(tok.value)[0]
  const m = /^\{(.+)\}$/.exec(v)
  if (m) {
    const target = byName[m[1]]
    if (!target) throw new Error(`unknown alias ${v} in ${tok.name}`)
    return valueFor(target, theme, depth + 1)
  }
  return v
}
const block = (sel, theme) => `${sel} {\n${colors.map((c) => `  --${c.name}: ${valueFor(c, theme)};`).join('\n')}\n}`
const scale = (fam) => (t[fam]?.tokens ?? []).map((x) => `  --${x.name}: ${x.value};`).join('\n')
const css = `/* Nagarro brand tokens — generated by scripts/sync-brand-tokens.mjs from the vendored
   Nagarro Master Slides tokens (${t.meta?.repo ?? 'Presentation_v1'} @ ${t.meta?.ref ?? '?'}). Do not edit by hand.
   Names are the Figma variable names: fg/50 → --fg-50, spacing/24 → --space-24, radius/15 → --radius-15. */

${block(':root, .nb-light', 'light')}

${block('.nb-dark', 'dark')}

:root {
${scale('spacing')}
${scale('radius')}
${scale('layout')}
${scale('weight')}
  --font-display: ${t.type.families.display};
  --font-body: ${t.type.families.body};
}
`
writeFileSync(resolve(root, 'src/styles/brand-tokens.css'), css)
console.log(`brand-tokens.css: ${colors.length} colours × 2 themes, ${(t.spacing?.tokens ?? []).length} spacing, ${(t.radius?.tokens ?? []).length} radius`)
