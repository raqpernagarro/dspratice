// handbook-md.tsx — writes the handbook as plain Markdown for AI tools to read (src/knowledge/handbook.md).
// The handbook's chapters (src/features/handbook/HandbookPage.tsx) are the source: this renders each
// one and keeps its words, headings, lists and tables, so the text people and machines read is the same.
//
//   npm run handbook:md
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { renderToStaticMarkup } from 'react-dom/server'
import { createElement } from 'react'
import { MemoryRouter } from 'react-router'
import { CHAPTERS } from '../src/features/handbook/HandbookPage'
import { client } from '../src/app/routes'

const entities: Record<string, string> = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#x27;': "'", '&#39;': "'", '&nbsp;': ' ' }
const text = (html: string) => html.replace(/<[^>]+>/g, '').replace(/&[#a-z0-9]+;/gi, (e) => entities[e] ?? e).replace(/\s+/g, ' ').trim()

function toMarkdown(html: string) {
  return html
    .replace(/<table>([\s\S]*?)<\/table>/g, (_m, t: string) => {
      const rows = [...t.matchAll(/<tr>([\s\S]*?)<\/tr>/g)].map((r) => [...r[1].matchAll(/<t[hd][^>]*>([\s\S]*?)<\/t[hd]>/g)].map((c) => text(c[1])))
      if (!rows.length) return ''
      const line = (r: string[]) => `| ${r.join(' | ')} |`
      return `\n\n${line(rows[0])}\n| ${rows[0].map(() => '---').join(' | ')} |\n${rows.slice(1).map(line).join('\n')}\n\n`
    })
    .replace(/<h2[^>]*>([\s\S]*?)<\/h2>/g, (_m, h: string) => `\n\n### ${text(h)}\n\n`)
    .replace(/<h3[^>]*>([\s\S]*?)<\/h3>/g, (_m, h: string) => `\n\n#### ${text(h)}\n\n`)
    .replace(/<li[^>]*>([\s\S]*?)<\/li>/g, (_m, l: string) => `\n- ${text(l)}`)
    .replace(/<p[^>]*>([\s\S]*?)<\/p>/g, (_m, p: string) => `\n\n${text(p)}\n\n`)
    .replace(/<[^>]+>/g, '')
    .replace(/&[#a-z0-9]+;/gi, (e) => entities[e] ?? e)
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

const r = client('demo-brand')
const parts = CHAPTERS.map((c) => {
  const html = renderToStaticMarkup(createElement(MemoryRouter, null, c.body(r)))
  return `## ${c.title}${c.internal ? ' (internal)' : ''}\n\n${toMarkdown(html)}`
})
const out = `# How we work: the Nagarro design systems handbook\n\nGenerated by \`npm run handbook:md\` from src/features/handbook/HandbookPage.tsx. Do not edit by hand. Chapters marked internal are for colleagues and AI tools, never for clients.\n\n${parts.join('\n\n')}\n`
writeFileSync(resolve(import.meta.dirname, '../src/knowledge/handbook.md'), out)
console.log(`Wrote src/knowledge/handbook.md: ${CHAPTERS.length} chapters, ${out.length} characters (about ${Math.round(out.length / 4)} tokens).`)
