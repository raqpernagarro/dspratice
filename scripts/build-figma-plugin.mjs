#!/usr/bin/env node
// Builds figma-plugin/code.js from the shared extractor + the plugin glue, so the plugin, the
// figma-cli adapter and the MCP capture all run the same extraction code.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
const dir = resolve(dirname(fileURLToPath(import.meta.url)), '../figma-plugin')
const code = `// GENERATED by scripts/build-figma-plugin.mjs — edit extract-text.js or plugin-glue.js instead.\n${readFileSync(resolve(dir, 'extract-text.js'), 'utf8')}\n${readFileSync(resolve(dir, 'plugin-glue.js'), 'utf8')}`
writeFileSync(resolve(dir, 'code.js'), code)
console.log('figma-plugin/code.js written')
