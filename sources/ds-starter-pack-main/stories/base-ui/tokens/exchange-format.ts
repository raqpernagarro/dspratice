/**
 * File formats exchanged between the Figma plugin (figma-plugin/) and the configurator.
 * No AI, no REST API: designers export from Figma, edit in the configurator, import back.
 *
 *  Figma ──(plugin Export)──▶ variables file ──(configurator Import)──▶ editor
 *  editor ──(configurator Export)──▶ change set ──(plugin Import)──▶ Figma
 *
 * Everything is matched by NAME (collection, mode, variable), never by id, so a change set
 * made from one file applies to any file that follows the same token spec.
 */

import type { SyncSection } from './figma-sync'

export const VARIABLES_FORMAT = 'ds-configurator/variables@1'
export const CHANGESET_FORMAT = 'ds-configurator/changes@1'

/* ------------------------------------------------- Figma → configurator */

export type FigmaAlias = { type: 'VARIABLE_ALIAS'; id: string }
export type FigmaColor = { r: number; g: number; b: number; a?: number }
/** Color with an aliased opacity (Figma's color + opacity composite). */
export type FigmaComposite = { color: FigmaAlias | FigmaColor; opacity?: FigmaAlias | number }
export type FigmaValue = FigmaAlias | FigmaColor | FigmaComposite | number | string | boolean

export interface FigmaVariableJson {
  id: string
  name: string
  variableCollectionId: string
  /** COLOR, FLOAT, STRING, BOOLEAN — and newer Figma types (e.g. EASING) passed through as-is. */
  resolvedType: 'COLOR' | 'FLOAT' | 'STRING' | 'BOOLEAN' | (string & {})
  description?: string
  scopes?: string[]
  valuesByMode: Record<string, FigmaValue>
}

export interface FigmaCollectionJson {
  id: string
  name: string
  modes: { modeId: string; name: string; parentModeId?: string }[]
  defaultModeId: string
  variableIds: string[]
  isExtension?: boolean
  parentVariableCollectionId?: string
  /** Extension collections: variable id → extension mode id → value. */
  variableOverrides?: Record<string, Record<string, FigmaValue>>
}

/** One layer property bound to a variable, inside one component variant. */
export interface AnatomyBinding {
  /** Layer path from the variant root, names joined by " › " ("" = the variant itself). */
  layer: string
  nodeType: string
  /** Figma field: topLeftRadius, paddingLeft, itemSpacing, fontSize, fills, strokes, … */
  field: string
  /** Bound variable, by name. */
  variable: string
}

/** What every variant of a component set is bound to (scanned by the plugin). */
export interface ComponentAnatomy {
  name: string
  /** Variant axes and their options, e.g. { Size: ['Large', 'Medium', 'Small'] }. */
  axes: Record<string, string[]>
  variants: { props: Record<string, string>; bindings: AnatomyBinding[] }[]
}

/** Same shape as Figma's REST `GET /variables/local` response, so existing tooling reads it. */
export interface VariablesExport {
  format: typeof VARIABLES_FORMAT
  fileName: string
  exportedAt: string
  meta: {
    variables: Record<string, FigmaVariableJson>
    variableCollections: Record<string, FigmaCollectionJson>
  }
  /** Component sets and their bindings (plugin exports only). */
  components?: ComponentAnatomy[]
  /** What the plugin remembers of the last sync (plugin exports from this version on). */
  sync?: SyncSection
}

/* ------------------------------------------------- configurator → Figma */

/**
 * A literal (hex/rgba color, number, string) or an alias to another variable by name. An alias with
 * `opacity` is Figma's color + opacity composite: the opacity is a variable name or a number.
 */
export type ChangeValue = string | number | boolean | { alias: string; collection?: string; opacity?: string | number }

/** A color linked to another primitive at an opacity (Figma's color + opacity variable). */
export type LinkedAlpha = { alias: string; opacity: string }

/** Create or update a primitive (e.g. a generated palette step). */
export interface PrimitiveChange {
  collection: string
  name: string
  type: 'COLOR' | 'FLOAT' | 'STRING'
  /** Literal, or for translucent colors a link to the base color + an opacity primitive. */
  value: string | number | LinkedAlpha
  description?: string
}

/** Marker in the description of every primitive the configurator generates (used for cleanup). */
export const GENERATED_MARKER = 'Generated by DS Configurator'

/** Set one variable's value in one mode. Brand extensions are addressed by their collection name. */
export interface ValueChange {
  collection: string
  variable: string
  mode: string
  value: ChangeValue
  /** Why: "Theme · Brand color", "Variables table", … (shown in the plugin preview). */
  reason?: string
}

/**
 * A component-level override: create or update a component token (aliasing a semantic token) and
 * bind the matching layers of the matching variants to it.
 */
export interface ComponentOverrideChange {
  /** Component set name in Figma ("Button"). */
  component: string
  /** Collection that holds component tokens ("components"). */
  collection: string
  /** Component token, e.g. "button/radius/lg". Created when missing. */
  token: string
  type: 'COLOR' | 'FLOAT' | 'STRING'
  /**
   * variable (default): create the token aliasing `alias` and bind the layers to it.
   * text-style: no token (a style isn't a variable); switch the layers' text style to the style
   * named `alias`, where they use one of the styles in `from`.
   */
  kind?: 'variable' | 'text-style'
  /** Semantic token (or, for text-style, the text style) it points at. */
  alias: string
  /** Variables those layers are bound to today. Only properties bound to one of these (or already
   *  to the token) are rebound; anything else in the matching layers is left alone. */
  from: string[]
  /** Every variant whose properties include these, e.g. { Size: "Large" }. */
  variants: Record<string, string>
  /** Layers to bind inside each matching variant ("" = the variant itself) and their fields. */
  layers: { layer: string; fields: string[] }[]
  reason?: string
}

/** Marker in the description of component tokens the configurator created. */
export const OVERRIDE_MARKER = 'Component override by DS Configurator'

export interface ChangeSet {
  format: typeof CHANGESET_FORMAT
  createdAt: string
  /** Theme name in the configurator. */
  source: string
  /** System version the change set was made from ("1.2"), when known. */
  version?: string
  /**
   * The modes the system ships, base first, as the semantic collection names them ("Light",
   * "Dark"). The plugin offers to add missing ones and to remove the others. Older change sets
   * have none: the file's modes are left as they are.
   */
  modes?: string[]
  /**
   * The system's extra brands, as collections extending the semantic one (the main brand is the
   * semantic collection itself). The plugin creates missing ones and offers to remove the others.
   * Older change sets have none: the file's brand collections are left as they are.
   */
  brands?: string[]
  primitives: PrimitiveChange[]
  values: ValueChange[]
  /** Component overrides (plugin creates the tokens, then rebinds layers). */
  components?: ComponentOverrideChange[]
}
