/**
 * Spec → Figma component set: builds every variant of a component with its build file
 * (scripts/ds/figma/<slug>.build.js: layer structure, named after the spec's parts), then binds all
 * layers per the spec. A build file may also define afterSet(set, h) (component properties) and
 * afterBind(set) (placement that depends on bound sizes). Writes a plugin snippet to run with figma-console `figma_execute`.
 *
 *   npm run ds:figma-build -- Input              → scripts/ds/.out/build-input.js
 *   npm run ds:figma-build -- Input --replace    → rebuilds an existing set in place
 */
import { existsSync, readFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { SPECS } from '../../stories/base-ui/spec'
import { RUNTIME_GUARD, bindRules, variantList } from './figma-snippets'
import { pickSpecs, root, writeSnippet } from './snippet-io'

const args = process.argv.slice(2)
const replace = args.includes('--replace')
const [spec] = pickSpecs(SPECS, args)
const buildFile = resolve(root, `scripts/ds/figma/${spec.slug}.build.js`)
if (!existsSync(buildFile)) throw new Error(`No build file: scripts/ds/figma/${spec.slug}.build.js`)

const state = spec.axes.find((a) => a.id === 'state')
const column = state ? { name: state.figma, values: state.values.map((v) => v.figma) } : null

writeSnippet(
  `build-${spec.slug}`,
  `// Generated by scripts/ds/figma-build.ts from ${spec.slug}.spec.ts + figma/${spec.slug}.build.js.
${RUNTIME_GUARD}
// ---- figma/${spec.slug}.build.js
${readFileSync(buildFile, 'utf8')}
// ----
// Variants, compactly: the axes once, then each variant's option indexes.
const AXES = ${JSON.stringify(spec.axes.map((a) => [a.id, a.figma, a.values.map((x) => [x.code, x.figma])]))};
const VARIANTS = ${JSON.stringify(variantList(spec).map(({ values }) => spec.axes.map((a) => a.values.findIndex((x) => x.code === values[a.id]))))}.map((ix) => ({
  props: Object.fromEntries(AXES.map(([, figma, vals], i) => [figma, vals[ix[i]][1]])),
  values: Object.fromEntries(AXES.map(([id, , vals], i) => [id, vals[ix[i]][0]])),
}));
const set = await buildSet(${JSON.stringify(spec.name)}, ${JSON.stringify(spec.name)}, VARIANTS, ${replace}, buildVariant, typeof afterSet === 'function' ? afterSet : null);
const [report] = await bindSpecs([${JSON.stringify({ name: spec.name, rules: bindRules(spec) })}], true);
const propsMissing = await applyFigmaProps(set, ${JSON.stringify(spec.figmaProps ?? [])});
if (typeof afterBind === 'function') await afterBind(set);
layoutSet(set, ${JSON.stringify(column)});
return { set: set.id, variants: set.type === 'COMPONENT_SET' ? set.children.length : 1, size: [Math.round(set.width), Math.round(set.height)], bind: { ok: report.ok, changed: report.changed, missing: report.missing, missingLayers: report.missingLayers, errors: report.errors }, propsMissing };
`,
)
