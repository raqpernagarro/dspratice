/**
 * Spec → Figma: writes a plugin snippet that binds every variant's layers to what the component
 * spec says (the same bindings the parity check expects and the code's token CSS uses).
 *
 *   npm run ds:figma-bind -- Button            → scripts/ds/.out/bind-button.js   (apply)
 *   npm run ds:figma-bind -- Button --check    → reports differences, changes nothing
 *
 * Run the snippet in the file (figma-console `figma_execute`). It only touches the fields the spec
 * lists; everything else on the layers is left alone.
 */
import { SPECS } from '../../stories/base-ui/spec'
import { RUNTIME_GUARD, bindRules } from './figma-snippets'
import { pickSpecs, writeSnippet } from './snippet-io'

const args = process.argv.slice(2)
const check = args.includes('--check')
const specs = pickSpecs(SPECS, args)
const payload = specs.map((s) => ({ name: s.name, rules: bindRules(s) }))

writeSnippet(
  `${check ? 'check' : 'bind'}-${specs.length === 1 ? specs[0].slug : 'all'}`,
  `// Generated by scripts/ds/figma-bind.ts — ${check ? 'check only' : 'applies bindings'}.
${RUNTIME_GUARD}
return await bindSpecs(${JSON.stringify(payload)}, ${!check});
`,
)
