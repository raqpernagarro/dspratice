// Maps the project's theme intents to DSN's own theme engine (site/lib/theme) and injects the
// result the way DSN's docs site does: doubled :root selectors outrank tokens.css.

import { DARK_SELECTOR, DEFAULT_BRAND, FONTS, LIGHT_SELECTOR, buildTheme, contrastChecks, ctaExactVars, ctaLightVars, datavizVars, defaultCta, themeVars, toCss, toDtcg, type ThemeOutput, type ThemeSettings } from '@dsn-theme/theme'
import type { ThemeIntents } from './intents'

export const DSN_STYLE_ID = 'udt-dsn-theme'

const hex6 = (hex: string) => {
  const h = hex.replace('#', '').trim()
  const full = h.length === 3 ? h.split('').map((c) => c + c).join('') : h
  return /^[0-9a-f]{6}$/i.test(full) ? full.toUpperCase() : DEFAULT_BRAND
}

export function dsnFontId(family: string): ThemeSettings['font'] {
  const f = family.trim().toLowerCase()
  if (!f || /equip/.test(f)) return 'default'
  const hit = FONTS.find((x) => x.label.toLowerCase() === f || (x.google ?? '').toLowerCase() === f)
  return (hit?.id as ThemeSettings['font']) ?? 'default'
}

/** Intents → DSN ThemeSettings. DSN's choices are discrete, so the mapping is a ladder. */
export function dsnSettings(i: ThemeIntents): ThemeSettings {
  const brand = hex6(i.brand.main)
  const isDefault = brand === DEFAULT_BRAND
  return {
    brand,
    cta: defaultCta(brand),
    neutral: i.neutralTint <= 0 ? 'gray' : i.neutralTint >= 0.5 ? 'match' : 'default',
    feedback: isDefault ? 'default' : 'harmonized',
    dataviz: isDefault ? 'default' : 'brand',
    font: dsnFontId(i.type.body),
    style: i.depth <= 0 ? 'flat' : i.depth <= 0.4 ? 'embossed' : 'soft',
    shape: i.buttonShape === 'pill' ? 'pill' : i.radius <= 0 ? 'square' : i.radius <= 6 ? 'subtle' : i.radius <= 18 ? 'rounded' : 'pill',
    density: i.density < 0.875 ? 'compact' : i.density < 1.125 ? 'default' : i.density < 1.375 ? 'comfortable' : 'spacious',
  }
}

const decl = (vars: Record<string, string>) =>
  Object.entries(vars)
    .map(([k, v]) => `${k}:${v}`)
    .join(';')

/** Variables DSN's engine does not cover: the body font when it is not in DSN's list, and the base size. */
function extraVars(i: ThemeIntents, settings: ThemeSettings): Record<string, string> {
  const vars: Record<string, string> = {}
  if (settings.font === 'default' && i.type.body && !/equip/i.test(i.type.body)) vars['--font-family-default'] = `'${i.type.body}', 'Equip', system-ui, sans-serif`
  return vars
}

export function dsnTheme(i: ThemeIntents): { settings: ThemeSettings; output: ThemeOutput } {
  const settings = dsnSettings(i)
  return { settings, output: buildTheme(settings) }
}

/** The style block for a frame's <head>. The light block re-points the CTA; the dark block the chart series. */
export function dsnStyleCss(i: ThemeIntents): string {
  const { settings, output: t } = dsnTheme(i)
  const root = { ...themeVars(t), ...extraVars(i, settings) }
  const light = { ...ctaLightVars(settings.cta), ...datavizVars(t, 'light') }
  return [
    `:root:root{${decl(root)}}`,
    `${LIGHT_SELECTOR}:root{${decl(light)}}`,
    `:root:root:root{${decl(ctaExactVars(t))}}`,
    `${DARK_SELECTOR}:root{${decl(datavizVars(t, 'dark'))}}`,
    `:root{font-size:${i.type.baseSize}px}`,
  ].join('')
}

/** Applies the theme to a document (the preview frame's). Idempotent. */
export function applyDsnTheme(doc: Document, i: ThemeIntents) {
  doc.documentElement.dataset.theme = i.mode
  let el = doc.getElementById(DSN_STYLE_ID) as HTMLStyleElement | null
  if (!el) {
    el = doc.createElement('style')
    el.id = DSN_STYLE_ID
    doc.head.appendChild(el)
  }
  el.textContent = dsnStyleCss(i)
}

/** Exports, for the token explorer and downloads. */
export function dsnExportCss(i: ThemeIntents) {
  return toCss(dsnTheme(i).output, 'generated by the Nagarro accelerator')
}
export function dsnExportDtcg(i: ThemeIntents) {
  return toDtcg(dsnTheme(i).output)
}
export function dsnContrast(i: ThemeIntents) {
  return contrastChecks(dsnTheme(i).output)
}

